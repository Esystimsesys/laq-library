/**
 * カタカナ・全角・大文字のゆれを吸収して、ひらがなの小文字に寄せる。
 * 中黒やスペースは、区切り方のゆれ（「ソフト・クリーム」「パトカー&バイク」）を
 * 消すために落とす。長音符は音の一部なので残す。
 */
export function normalize(text) {
  return String(text ?? '')
    .normalize('NFKC')
    .toLowerCase()
    .replace(/[ァ-ヶ]/g, (c) => String.fromCharCode(c.charCodeAt(0) - 0x60))
    .replace(/[・\s&＿_]/g, '')
}

