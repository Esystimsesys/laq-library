/** ルールでは直せない少数の作品を、作品名（正規化後）で名指しで補正する。 */
const OVERRIDES = {
  大遣唐使展記念作品: ['のりもの'], // 遣唐使船の作品
  こんぼいへっど: ['のりもの', 'キャラクター・くうそう'],
  あん: ['キャラクター・くうそう'], // LaQ のキャラクター
}

function matches(text, keyword) {
  return keyword instanceof RegExp ? keyword.test(text) : text.includes(keyword)
}

function collect(text) {
  const found = []
  for (const [category, keywords] of RULES) {
    if (keywords.some((k) => matches(text, k))) found.push(category)
  }
  return found
}

/**
 * 作品名を主に見てカテゴリを決める。作品名で何も当たらなかったときだけ、
 * 説明文まで広げて拾う（説明文は前置きが長く、先に見ると誤爆しやすい）。
 */
export function categorize(title, description = '') {
  const normalizedTitle = normalize(title)

  const override = Object.hasOwn(OVERRIDES, normalizedTitle) ? OVERRIDES[normalizedTitle] : null
  if (override) return [...override]

  let found = collect(normalizedTitle)
  if (found.length === 0) found = collect(normalize(description))
  if (found.length === 0) return [OTHER]

  return CATEGORIES.filter((c) => found.includes(c))
}
