import { test, expect } from '@playwright/test'
test('スマホの接続矢印は分解に追従し、接続点が近い向きでは非表示になる', async ({ page }) => {
  test.setTimeout(60000)
  await page.goto('./assembly/metamon?step=assembly:0')
  const iframe = page.locator('iframe'), viewer = page.frameLocator('iframe')
  await expect(iframe).toHaveAttribute('data-shown', 'assembly:0', { timeout: 30000 })
  await expect(viewer.locator('#guide')).toBeHidden()
  await expect(viewer.locator('#show-connections')).toBeHidden()
  const arrows=viewer.locator('#stage .connection-path')
  await viewer.locator('#explode').fill('0')
  await viewer.locator('#explode').dispatchEvent('input')
  await expect(arrows).toHaveCount(0)
  await viewer.locator('#explode').fill('1')
  await viewer.locator('#explode').dispatchEvent('input')
  await expect(arrows).toHaveCount(0)
  await viewer.locator('#explode').fill('100')
  await viewer.locator('#explode').dispatchEvent('input')
  // 初期表示は「まえ」（docs/ASSEMBLIES.md）。この手順は奥へ はなれるので、正面からは接続点が重なり矢印を出さない
  await expect(arrows).toHaveCount(0)
  await viewer.getByText('むきを かえる・すかして見る', { exact: true }).click()
  await viewer.getByRole('button', { name: 'ななめ', exact: true }).click()
  await expect(arrows).toHaveCount(2)
  await expect(viewer.locator('#stage .connection-arrow text')).toHaveCount(0)
  await viewer.getByRole('button', { name: 'まえ', exact: true }).click()
  await expect(arrows).toHaveCount(0)
  await viewer.getByRole('button', { name: 'ななめ', exact: true }).click()
  await expect(arrows).toHaveCount(2)
  await viewer.locator('#stage').focus()
  await page.keyboard.press('ArrowRight')
  await expect(arrows).toHaveCount(2)
  for(const value of ['0','1','100']){
    await viewer.locator('#explode').fill(value)
    await viewer.locator('#explode').dispatchEvent('input')
    await expect(arrows).toHaveCount(value==='100'?2:0)
  }
  // Exercise the native range thumb in both Chromium and WebKit, not only fill().
  const slider=viewer.locator('#explode'),box=(await slider.boundingBox())!
  await page.mouse.move(box.x+box.width-8,box.y+box.height/2);await page.mouse.down()
  await page.mouse.move(box.x+8,box.y+box.height/2,{steps:12});await page.mouse.up()
  await expect(slider).toHaveValue('0');await expect(arrows).toHaveCount(0)
  const frame=page.frames().find(f=>f.url().includes('/assemblies/viewer/'))!
  const sizes=await frame.evaluate(()=>[document.documentElement.scrollWidth,document.documentElement.clientWidth])
  expect(sizes[0]).toBe(sizes[1])
})


test.describe('はなして見るの操作',()=>{
 test.use({hasTouch:true})
 for(const width of [390,1240])test(`分解スライダーをタップ・ドラッグ・ボタンで調節できる ${width}px`,async({page})=>{
  test.setTimeout(90000)
  await page.setViewportSize({width,height:844})
  await page.goto('./assembly/metamon?step=assembly:6')
  await expect(page.locator('iframe')).toHaveAttribute('data-shown','assembly:6',{timeout:30000})
  const frame=page.frames().find(f=>f.url().includes('/assemblies/viewer/'))!,slider=frame.getByRole('slider',{name:'はなして見る度合い'})
  await expect(frame.locator('#explode-value')).toHaveText('65%')
  await slider.press('Home')
  await expect(slider).toBeFocused()
  expect(await slider.evaluate(el=>getComputedStyle(el).outlineStyle)).toBe('solid')
  await slider.scrollIntoViewIfNeeded()
  const box=(await slider.boundingBox())!
  expect(box.height).toBeGreaterThanOrEqual(48);expect(box.width).toBeGreaterThanOrEqual(180)
  const less=frame.getByRole('button',{name:'はなす度合いを10%へらす'}),more=frame.getByRole('button',{name:'はなす度合いを10%ふやす'})
  await expect(less).toBeDisabled();await expect(frame.locator('#explode-value')).toHaveText('0%')
  const moreBox=(await more.boundingBox())!;expect(moreBox.width).toBeGreaterThanOrEqual(44);expect(moreBox.height).toBeGreaterThanOrEqual(44)
  await more.click();await expect(slider).toHaveValue('10');await expect(frame.locator('#explode-value')).toHaveText('10%')
  await less.click();await expect(slider).toHaveValue('0')
  // Tapping the track, keyboard endpoints and button clamping all reach the same model state.
  await page.touchscreen.tap(box.x+box.width*.7,box.y+box.height/2)
  expect(Number(await slider.inputValue())).toBeGreaterThan(50)
  await slider.press('End');await expect(slider).toHaveValue('100');await expect(more).toBeDisabled()
  await slider.press('ArrowLeft');await more.click();await expect(slider).toHaveValue('100')
  await slider.press('Home');await expect(slider).toHaveValue('0');await expect(less).toBeDisabled()
  await slider.press('ArrowRight');await less.click();await expect(slider).toHaveValue('0')
  await more.click()
  const readView=()=>frame.evaluate(async()=>{await new Promise(requestAnimationFrame);return (window as any).__unitGuide()})
  const beforeRotate=await readView(),stage=frame.locator('#stage')
  expect(beforeRotate.explode).toBe(.1)
  await stage.scrollIntoViewIfNeeded()
  const stageBox=(await stage.boundingBox())!
  await page.mouse.move(stageBox.x+stageBox.width/2,stageBox.y+stageBox.height/2);await page.mouse.down()
  await page.mouse.move(stageBox.x+stageBox.width/2+40,stageBox.y+stageBox.height/2+20,{steps:4});await page.mouse.up()
  expect((await readView()).screenBounds).not.toEqual(beforeRotate.screenBounds)
  await frame.getByRole('button',{name:'＋ 大きく',exact:true}).click()
  expect((await readView()).zoom).toBeGreaterThan(beforeRotate.zoom);await expect(slider).toHaveValue('10')
  await page.getByRole('button',{name:'つぎへ →',exact:true}).click()
  await expect(page.locator('iframe')).toHaveAttribute('data-shown','unit:D2:0')
  await expect(slider).toHaveValue('0');await expect(frame.locator('#explode-value')).toHaveText('0%');await expect(less).toBeDisabled()
  await frame.locator('.toolbar').screenshot({path:`test-results/separation-control-${width}.png`})
  // Native drag still reaches both endpoints with the enlarged thumb.
  await slider.press('End');await slider.scrollIntoViewIfNeeded()
  const dragBox=(await slider.boundingBox())!
  await page.mouse.move(dragBox.x+dragBox.width-16,dragBox.y+dragBox.height/2);await page.mouse.down()
  await page.mouse.move(dragBox.x+dragBox.width/2,dragBox.y+dragBox.height/2,{steps:12})
  const middle=Number(await slider.inputValue());expect(middle).toBeGreaterThan(25);expect(middle).toBeLessThan(75)
  expect((await readView()).explode).toBe(middle/100)
  await page.mouse.move(dragBox.x+16,dragBox.y+dragBox.height/2,{steps:12});await page.mouse.up()
  await expect(slider).toHaveValue('0');expect((await readView()).explode).toBe(0)
  const sizes=await frame.evaluate(()=>[document.documentElement.scrollWidth,document.documentElement.clientWidth])
  expect(sizes[0]).toBe(sizes[1])
 })
})
